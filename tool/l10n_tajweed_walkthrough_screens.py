def set_key(text: str, key: str, value: str) -> str:
    pattern = rf'(  "{re.escape(key)}": )".*?"'
    replacement = rf"\1{json.dumps(value, ensure_ascii=False)}"
    new_text, count = re.subn(pattern, replacement, text, count=1)
    if count != 1:
        raise SystemExit(f"failed to set {key}")
    return new_text


def insert_missing(text: str, values: dict[str, str]) -> str:
    missing = {k: v for k, v in values.items() if f'"{k}"' not in text}
    if not missing:
        return text
    pattern = rf'(  "{ANCHOR}": .*?,)\n'
    match = re.search(pattern, text)
    if not match:
        raise SystemExit("anchor missing")
    lines = [
        f'  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)},'
        for key, value in missing.items()
    ]
    return text[: match.end()] + "\n".join(lines) + "\n" + text[match.end() :]


def main() -> None:
    for path in sorted(ROOT.glob("app_*.arb")):
        locale = path.stem.removeprefix("app_")
        if locale == "en":
            continue
        text = path.read_text(encoding="utf-8")
        for key, value in FEATURE_DEMO.get(locale, {}).items():
            if f'"{key}"' in text:
                text = set_key(text, key, value)
        if locale in SCREEN_STRINGS:
            text = insert_missing(text, SCREEN_STRINGS[locale])
        path.write_text(text, encoding="utf-8")
        print(f"updated {path.name}")


if __name__ == "__main__":
    main()

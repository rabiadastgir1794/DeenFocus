    /**
     * Regression: reciting a completely different ayah (zero shared words after
     * normalize) must yield near-zero lexical accuracy — the failure mode that
     * forced-align-first scoring produced 75–100% on.
     */
    @Test
    fun completelyDifferentAyahYieldsZeroLexicalAccuracy() {
        val expected = TajweedLexicalScoring.splitWords("قُلْ هُوَ اللَّهُ أَحَدٌ")
        val hypothesis = TajweedLexicalScoring.splitWords("مَالِكِ يَوْمِ الدِّينِ")
        val ops = TajweedLexicalScoring.alignWords(expected, hypothesis)
        assertEquals(0, ops.count { it.op == TajweedLexicalScoring.LexicalOp.MATCH })
        assertTrue(ops.any { it.op == TajweedLexicalScoring.LexicalOp.SUB || it.op == TajweedLexicalScoring.LexicalOp.MISS })
        val tokens = TajweedLexicalScoring.tokensFromAlignment(ops)
        assertFalse(tokens.any { it["status"] == "ok" || it["status"] == "minor" || it["status"] == "major" })
        assertTrue(tokens.any { it["status"] == "sub" || it["status"] == "miss" })
        assertEquals(0.0, TajweedLexicalScoring.wordAccuracyFromTokens(tokens, expected.size), 0.0001)
        assertEquals(0.0, TajweedLexicalScoring.wordAccuracyScore(expected, hypothesis), 0.0001)
    }

    @Test
    fun substitutionStatusIsDistinctFromMajorPronunciation() {
        val ops = TajweedLexicalScoring.alignWords(
            listOf("قُلْ", "هُوَ"),
            listOf("مَالِكِ", "يَوْمِ"),
        )
        val tokens = TajweedLexicalScoring.tokensFromAlignment(ops)
        assertTrue(tokens.all { it["status"] == "sub" })
        assertTrue(tokens.all { it["lexical"] == "sub" })
        assertTrue(tokens.all { it["pronunciation"] == null })
        // Combined UI "major" means bad pronunciation of a *matched* word — not substitution.
        assertFalse(tokens.any { it["status"] == "major" })
    }

    /**
     * Matched words keep a separate pronunciation field; UI status mirrors it, but
     * lexical accuracy still counts the match even when pronunciation is "major".
     */
    @Test
    fun matchedWordPreservesPronunciationSeparatelyFromLexicalAccuracy() {
        val base = TajweedLexicalScoring.tokenMap(
            text = "قُلْ",
            status = "ok",
            lexical = "match",
            pronunciation = "ok",
            prob = 1.0f,
        ).toMutableMap()
        val badPron = PronunciationHeadModel.statusForProb(0.2f) // "major"
        base["status"] = badPron
        base["pronunciation"] = badPron
        base["prob"] = 0.2f

        assertEquals("match", base["lexical"])
        assertEquals("major", base["pronunciation"])
        assertEquals("major", base["status"])
        assertEquals(1.0, TajweedLexicalScoring.wordAccuracyFromTokens(listOf(base), 1), 0.0001)
    }

    @Test
    fun alignWordsDetectsMissAndExtra() {
        val ops = TajweedLexicalScoring.alignWords(
            listOf("أ", "ب", "ج"),
            listOf("أ", "ج", "د"),
        )
        // A match, B miss or A-B-C vs A-C-D → A match, B miss, C match? 
        // Actually: أ=أ match, ب vs ج = sub, ج vs د = sub — or miss+extra depending on costs.
        // Equal-cost: replace is preferred in our backtrace when cost=1 vs delete+insert=2.
        assertEquals(1, ops.count { it.op == TajweedLexicalScoring.LexicalOp.MATCH })
        assertTrue(
            ops.any { it.op == TajweedLexicalScoring.LexicalOp.SUB } ||
                (ops.any { it.op == TajweedLexicalScoring.LexicalOp.MISS } &&
                    ops.any { it.op == TajweedLexicalScoring.LexicalOp.EXTRA }),
        )
    }


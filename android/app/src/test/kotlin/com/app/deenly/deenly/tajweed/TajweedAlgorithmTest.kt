    @Test
    fun sentencePieceTokenizerRoundTripsSimpleVocab() {
        val tmp = File.createTempFile("tokens_${UUID.randomUUID()}", ".txt")
        tmp.writeText("<unk> 0\n\u2581\u0628\u0633\u0645 1\n\u2581\u0627\u0644\u0644\u0647 2\n\u0645 3\n")
        try {
            val tokenizer = SentencePieceTokenizer(tmp)
            val ids = tokenizer.encode("\u0628\u0633\u0645 \u0627\u0644\u0644\u0647")
            assertTrue(ids.isNotEmpty())
            val decoded = tokenizer.decode(ids)
            assertTrue(decoded.contains("\u0628\u0633\u0645"))
        } finally {
            tmp.delete()
        }
    }

    /**
     * The forced-align -> word-grouping pipeline (TajweedEngine.buildWordLevelTokens) relies
     * on `startsNewWord` to know which pieces begin a new Quran word — this pins that raw
     * "▁" boundary detection independent of the head-model-dependent aggregation.
     */
    @Test
    fun startsNewWordDetectsSentencePieceWordBoundary() {
        val tmp = File.createTempFile("tokens_${UUID.randomUUID()}", ".txt")
        // ids: 0=<unk> 1=▁بسم(word start) 2=▁الله(word start) 3=م(continuation, no ▁)
        tmp.writeText("<unk> 0\n\u2581\u0628\u0633\u0645 1\n\u2581\u0627\u0644\u0644\u0647 2\n\u0645 3\n")
        try {
            val tokenizer = SentencePieceTokenizer(tmp)
            assertTrue(tokenizer.startsNewWord(1))
            assertTrue(tokenizer.startsNewWord(2))
            assertFalse(tokenizer.startsNewWord(3))
            assertFalse(tokenizer.startsNewWord(99)) // out-of-range id must not throw
        } finally {
            tmp.delete()
        }
    }

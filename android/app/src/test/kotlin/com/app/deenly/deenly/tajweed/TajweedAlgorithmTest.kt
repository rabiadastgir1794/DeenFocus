    /** Full Al-Fatiha 1:4 Uthmani (app expected) ↔ Imlaei ASR hyp — previously all SUB. */
    @Test
    fun normalizeArabicFatihah14UthmaniMatchesImlaeiAsr() {
        val uthmaniExpected = "مَٰلِكِ يَوۡمِ ٱلدِّينِ"
        val asrHypothesis = "مَالِكِ يَوْمِ الدِّينِ"
        val expWords = TajweedLexicalScoring.splitWords(uthmaniExpected)
        val hypWords = TajweedLexicalScoring.splitWords(asrHypothesis)
        assertEquals(3, expWords.size)
        assertEquals(3, hypWords.size)
        for (i in expWords.indices) {
            assertEquals(
                "word[$i] must match after normalize",
                TajweedLexicalScoring.normalizeArabic(expWords[i]),
                TajweedLexicalScoring.normalizeArabic(hypWords[i]),
            )
        }
        val ops = TajweedLexicalScoring.alignWords(expWords, hypWords)
        assertEquals(3, ops.size)
        assertTrue(ops.all { it.op == TajweedLexicalScoring.LexicalOp.MATCH })
        assertEquals(1.0, TajweedLexicalScoring.wordAccuracyScore(expWords, hypWords), 0.0001)
    }


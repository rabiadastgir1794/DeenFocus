    /**
     * Lexical-first: wordAccuracy counts lexical matches only. Pronunciation severity
     * (minor/major on a matched word) must NOT reduce the percentage.
     */
    @Test
    fun wordAccuracyFromTokensIsLexicalOnlyIgnoringPronunciationSeverity() {
        val tokens = listOf(
            mapOf("text" to "بِسْمِ", "status" to "ok", "lexical" to "match", "pronunciation" to "ok"),
            mapOf("text" to "اللَّهِ", "status" to "minor", "lexical" to "match", "pronunciation" to "minor"),
            mapOf("text" to "الرَّحْمَٰنِ", "status" to "major", "lexical" to "match", "pronunciation" to "major"),
            mapOf("text" to "الرَّحِيمِ", "status" to "miss", "lexical" to "miss", "pronunciation" to null),
        )
        // 3 of 4 expected words were lexically matched (ok/minor/major combined UI status).
        assertEquals(0.75, TajweedLexicalScoring.wordAccuracyFromTokens(tokens, 4), 0.0001)
    }


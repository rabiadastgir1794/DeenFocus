    @Test
    fun melFrontendProducesExpectedFrameCountAndBucket() {
        val sampleCount = MelFrontend.SAMPLE_RATE // 1 second of audio
        val pcm = FloatArray(sampleCount) { i -> kotlin.math.sin(i * 0.01).toFloat() }
        val result = MelFrontend.logMel(pcm)
        assertEquals(MelFrontend.N_MELS * result.time, result.features.size)
        assertTrue(result.time > 0)

        val bucket = MelFrontend.padToBucket(result.features, result.time)
        assertTrue(bucket.bucketT >= result.time)
        assertEquals(MelFrontend.N_MELS * bucket.bucketT, bucket.padded.size)
        assertTrue(listOf(80, 160, 320, 640, 1280, 2560, 4800).contains(bucket.bucketT))
    }

    /**
     * Golden-vector parity check against tajweed-lab/web/asr/mel.py (the Python reference
     * the ONNX encoder was actually calibrated against — see COREML_CONTRACT.md's "mel
     * parity gate"). Values below were generated by running the reference on the exact
     * same synthetic 440 Hz tone: see the Phase 3 validation notes in
     * memory/features/tajweed/overview.md for the generating command.
     */
    @Test
    fun melFrontendMatchesPythonReferenceOnSyntheticTone() {
        val n = MelFrontend.SAMPLE_RATE
        val pcm = FloatArray(n) { i ->
            val t = i.toDouble() / MelFrontend.SAMPLE_RATE
            (0.3 * kotlin.math.sin(2.0 * Math.PI * 440.0 * t)).toFloat()
        }
        val result = MelFrontend.logMel(pcm)
        assertEquals(101, result.time)

        val expected = mapOf(
            (0 to 0) to 5.030645,
            (0 to 1) to 3.264629,
            (0 to 50) to -0.196291,
            (0 to 99) to 4.572105,
            (10 to 0) to 5.151812,
            (10 to 1) to 3.513548,
            (10 to 50) to -0.196221,
            (10 to 99) to 4.576383,
            (40 to 0) to 7.199261,
            (40 to 1) to 4.668607,
            (40 to 50) to -0.189172,
            (40 to 99) to 2.038765,
            (79 to 0) to 8.097102,
            (79 to 1) to 5.592010,
            (79 to 50) to -0.156101,
            (79 to 99) to 0.117211,
        )
        for ((key, expectedValue) in expected) {
            val (m, t) = key
            val actual = result.features[m * result.time + t]
            assertEquals(
                "mel[$m,$t] should match Python reference",
                expectedValue,
                actual.toDouble(),
                0.01,
            )
        }
    }


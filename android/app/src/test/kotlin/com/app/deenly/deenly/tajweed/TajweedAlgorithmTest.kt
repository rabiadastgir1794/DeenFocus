    @Test
    fun ctcAlignerProducesMonotonicIntervalsForSyntheticLogprobs() {
        // CtcAligner hardcodes blankId = 1024 (same as iOS), so the synthetic vocab
        // must be wider than that even though only 3 ids are actually exercised.
        val blank = CtcAligner.BLANK_ID
        val vocab = blank + 1
        val t = 8
        val logprobs = Array(t) { FloatArray(vocab) { -5f } }
        val favored = mapOf(0 to 0, 1 to 0, 2 to 0, 3 to 1, 4 to 1, 5 to 1, 6 to blank, 7 to blank)
        for (i in 0 until t) {
            logprobs[i][favored.getValue(i)] = 0f
        }
        val intervals = CtcAligner.forcedAlign(logprobs, listOf(0, 1))
        assertEquals(listOf(0, 1), intervals.map { it.tokenId })
        // tokenIndex (position within the input tokenIds list) is what word-grouping keys
        // off — must track tokenId 1:1 here since there are no duplicate ids in this vocab.
        assertEquals(listOf(0, 1), intervals.map { it.tokenIndex })
        assertTrue(intervals[0].endFrame <= intervals[1].startFrame + 1)
        assertTrue(intervals[1].endFrame > intervals[0].startFrame)
    }

    @Test
    fun lexicalTokenReportMatchesAdr006Shape() {
        val expected = listOf("بِسْمِ", "اللَّهِ")
        val hypothesis = listOf("بِسْمِ", "اللَّهِ")
